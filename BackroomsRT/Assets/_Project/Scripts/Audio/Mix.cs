namespace Backrooms.Audio
{
    /// <summary>
    /// 音量の基準。
    ///
    /// 一つずつ耳で決めると全体のバランスが取れない。実際うるさすぎた。
    /// 相対値は実測の音圧レベルから出す。オフィスでの代表値は
    ///     カーペット上の足音 (耳の位置)      48 dBA
    ///     空調の吹き出し (NC-35 のオフィス)  38 dBA
    ///     磁気安定器 1 台 2.5m               32 dBA
    ///     部屋の暗騒音                       30 dBA
    /// 足音を 0dB としたときの相対は -10 / -16 / -18 dB になる。
    ///
    /// 絶対の音量を決めるのは Output ひとつだけ。カムコーダの AGC が
    /// 最後に均してしまうので、ここで実際に効くのは比と、AGC の目標値。
    /// 前は目標が 0.14 rms で、静かな部屋を音楽並みまで持ち上げていた。
    /// </summary>
    public static class Mix
    {
        /// <summary>足音。基準 (0 dB)。</summary>
        public const float Step = 0.110f;

        /// <summary>空調。-10 dB。</summary>
        public const float Hvac = 0.035f;

        /// <summary>
        /// 蛍光灯 1 台。導出は -16dB = 0.017 だが、実際には近くの数台が
        /// 非同期に足し合わさるうえ、これが Backrooms で一番効く音なので
        /// +1.5dB だけ上に置いている。
        /// </summary>
        public const float Ballast = 0.020f;

        /// <summary>部屋の暗騒音。-18 dB。</summary>
        public const float Tone = 0.014f;

        /// <summary>
        /// 撮っている人の呼吸。安静時の呼吸そのものは 10-25dBA しかないが、
        /// マイクは胸の高さで口から 30cm と離れていない。実際のカムコーダの
        /// 記録では常に入っている。部屋の暗騒音 (30dBA) より上、
        /// 空調 (38dBA) より下に置く。素材は peak 0.85 / rms 0.127 に揃えてある。
        /// </summary>
        /// 0.045 だと部屋の床 (安定器 + 暗騒音 + 空調の合計) と同じ大きさ
        /// (+0.6dB) になった。15 分ずっと鳴っているものなので 3dB 下げる。
        public const float Breath = 0.032f;

        /// <summary>
        /// イベントの音。爆音で入れる。素材は peak 0.95 に揃えてあるので、
        /// これがそのまま最大の振幅になる。カムコーダの AGC は 0.12 秒で
        /// 叩き落としにかかるが、頭の一撃は必ず通る — 実機で大きな音が
        /// 入ったときのあれが、そのまま演出になる。
        /// 0.60 では AGC が 0.25 まで絞り込むぶんを含めて出力が 0.317 までしか
        /// 伸びなかった。Tape 側に飽和を入れて 1.0 で折り返さないようにしたので、
        /// ここは素材の頭 (peak 0.95) をそのまま通す値に置く。実際の音量は
        /// PanicEvent が AGC の下限を 1.0 まで開けることで決まる。
        /// </summary>
        public const float Sting = 0.95f;

        /// <summary>
        /// 落ちて床に倒れる音。自分の体がぶつかる音なので、部屋のどの音よりも
        /// 近い。Sting と同じく、実際の大きさを決めているのは AGC の下限。
        /// </summary>
        public const float Impact = 0.85f;

        /// <summary>
        /// 自分の叫び声。耳の位置では 85dBA 前後で、足音の +37dB になる。
        /// そのまま入れると 7.8 になって必ず振り切れる。実機のマイクは
        /// この時点で飽和していて、AGC が 0.12 秒で叩き落とす — それが
        /// カムコーダで叫んだときのあの音だが、デジタルで 1.0 を超えると
        /// 飽和ではなく単なる破綻になる。控えめから始める。
        /// </summary>
        /// 0.35 では部屋の暗騒音に対して +9.2dB しか無く、叫びに聞こえなかった。
        public const float Shout = 0.55f;

        /// <summary>
        /// 叫びが部屋から返ってくる量。自分の口は自分の耳のすぐそばなので、
        /// 直接音のほうが圧倒的に大きい (残響半径の内側にいる)。
        /// 直接音に対して -16dB あたりを狙う。
        /// </summary>
        public const float ShoutSend = 0.25f;

        /// <summary>
        /// 遠くの声の直接音。25m 先で壁を挟めばほとんど残らない。
        /// これは「どちらから聞こえたか」を残すためだけの量。
        /// </summary>
        public const float VoiceFarDirect = 0.030f;

        /// <summary>
        /// 遠くの声が部屋を回って返ってくる量。遠い声はこちらが主になる。
        /// 残響音場は距離でほとんど減らないので、直接音と違って
        /// 離れても残る。ここが「反響してきた声」の本体。
        /// </summary>
        public const float VoiceFarSend = 0.35f;

        /// <summary>
        /// 最終的な音量 = AGC の目標 rms。うるさい／小さいはここだけ動かす。
        ///
        /// 0.012 は -38 dBFS。最初は 0.14 (-17 dBFS) で、静かな部屋を
        /// 音楽並みまで持ち上げていた。0.028 にしたら今度は音源側が
        /// 下がりすぎて AGC が上限に張り付き、まったく動かなくなった。
        /// 張り付いた AGC はただの固定利得で、カムコーダらしさが消える。
        /// 素の混合が 0.0035 rms なので、3.4 倍で届く 0.012 に置く。
        /// </summary>
        public const float Output = 0.012f;

        /// <summary>テープのヒス。出力を下げたぶん一緒に下げる。</summary>
        public const float Hiss = 0.0010f;

        /// <summary>
        /// AGC が掛けられる最大の利得。目標に届く値より上に置くこと。
        /// 届かないと常に上限に張り付き、足音で絞られることもなくなる。
        /// </summary>
        public const float AgcMaxGain = 5.0f;
    }
}
